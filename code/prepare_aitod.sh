#!/usr/bin/env bash
# =============================================================================
#  AI-TODv2 数据准备：解压图像 → 生成 YOLO 标签 → 写 data.yaml → 冒烟前置检查
#
#  目录约定（ultralytics 靠把路径里的 /images/ 换成 /labels/ 找标签）：
#      ~/data/AI-TOD/
#        images/train/*.png      labels/train/*.txt
#        images/val/*.png        labels/val/*.txt
#        annotations_v2/aitod_{train,val}_v2.json
#        yolo/{train,val}.txt    yolo/aitod.yaml
#
#  用法： bash prepare_aitod.sh
# =============================================================================
set -uo pipefail

D="$HOME/data/AI-TOD"
RAW="$D/raw"
CONV="/mnt/d/WorkBuddy/BING/LTNet/code/LTDNet-main/tools/misc/aitod2yolo.py"
PY="${PY:-/root/venv/torch/bin/python}"
CLASSES="airplane bridge storage-tank ship swimming-pool vehicle person wind-mill"

fail() { echo "[FAIL] $*"; exit 1; }

# ---------------------------------------------------------------- 1. 解压
unpack() {
  local zip="$1" split="$2"
  local dst="$D/images/$split"
  if [ -d "$dst" ] && [ "$(find "$dst" -name '*.png' 2>/dev/null | head -1)" ]; then
    echo "[skip] $split 图像已存在：$(find "$dst" -name '*.png' | wc -l) 张"
    return 0
  fi
  local tmp="$D/_tmp_$split"
  rm -rf "$tmp"; mkdir -p "$tmp"
  echo "[unzip] $zip"
  unzip -q -o "$zip" -d "$tmp" || fail "解压 $zip 失败"

  # 压缩包内部结构不固定：找出含 png 的最深公共目录
  local src
  src="$(find "$tmp" -name '*.png' -printf '%h\n' 2>/dev/null | sort -u | head -1)"
  [ -n "$src" ] || fail "$zip 里没有 png"
  local n
  n=$(find "$tmp" -name '*.png' | wc -l)
  echo "  png=$n  目录=$src"

  mkdir -p "$dst"
  find "$tmp" -name '*.png' -exec mv -t "$dst" {} + || fail "移动 $split 图像失败"
  rm -rf "$tmp"
  echo "  -> $dst  $(find "$dst" -name '*.png' | wc -l) 张"
}

mkdir -p "$D/images" "$D/labels" "$D/yolo"
[ -f "$RAW/train.zip" ] || fail "缺 $RAW/train.zip（先跑 dl_images.sh）"
[ -f "$RAW/val.zip" ]   || fail "缺 $RAW/val.zip"

unpack "$RAW/train.zip" train
unpack "$RAW/val.zip"   val

# ---------------------------------------------------------------- 2. 转 YOLO
conv() {
  local split="$1" ann="$2"
  [ -f "$ann" ] || fail "缺标注 $ann"
  echo "[convert] $split"
  "$PY" "$CONV" \
    --ann "$ann" --split-names "$split" \
    --img-root "$D/images/$split" \
    --out-labels "$D/labels/$split" \
    --out-list "$D/yolo" \
    --classes $CLASSES 2>&1 | tail -12
}

conv train "$D/annotations_v2/aitod_train_v2.json"
conv val   "$D/annotations_v2/aitod_val_v2.json"

# ---------------------------------------------------------------- 3. data.yaml
cat > "$D/yolo/aitod.yaml" <<YAML
# AI-TODv2 (official train/val split), generated by prepare_aitod.sh
path: $D
train: yolo/train.txt
val: yolo/val.txt
names:
$(i=0; for c in $CLASSES; do echo "  $i: $c"; i=$((i+1)); done)
YAML

echo "=== data.yaml ==="
cat "$D/yolo/aitod.yaml"

# ---------------------------------------------------------------- 4. 前置检查
echo "=== 一致性检查 ==="
echo "train 图像: $(find "$D/images/train" -name '*.png' | wc -l)  标签: $(find "$D/labels/train" -name '*.txt' | wc -l)  清单行: $(wc -l < "$D/yolo/train.txt")"
echo "val   图像: $(find "$D/images/val"   -name '*.png' | wc -l)  标签: $(find "$D/labels/val"   -name '*.txt' | wc -l)  清单行: $(wc -l < "$D/yolo/val.txt")"
du -sh "$D/images" "$D/labels" 2>/dev/null

# 标签坐标必须在 [0,1]；类别必须在 0..7
"$PY" - <<'PY'
import glob, os, sys
D = os.path.expanduser('~/data/AI-TOD')
bad_coord = bad_cls = empty = total = 0
for split in ('train', 'val'):
    files = glob.glob(os.path.join(D, 'labels', split, '*.txt'))
    for f in files:
        with open(f, encoding='utf-8') as fh:
            lines = [l for l in fh.read().split('\n') if l.strip()]
        if not lines:
            empty += 1
            continue
        for l in lines:
            p = l.split()
            total += 1
            if len(p) != 5:
                bad_coord += 1
                continue
            c = int(float(p[0]))
            v = [float(x) for x in p[1:]]
            if not (0 <= c <= 7):
                bad_cls += 1
            if any(x < 0 or x > 1 for x in v):
                bad_coord += 1
print('标签文件中的空文件（纯背景，允许）:', empty)
print('总框数:', total, '| 坐标越界:', bad_coord, '| 类别越界:', bad_cls)
sys.exit(1 if (bad_coord or bad_cls) else 0)
PY
rc=$?
[ $rc -eq 0 ] || fail "标签检查不通过"
echo "=== READY ==="
